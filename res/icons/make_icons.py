"""Build the selector's glyph masks for the emulator.

Emits:

  MREmu/NativeApps/Menu/IconsData.h    8-bit coverage masks, not PNGs

Why masks and not the PNGs themselves
-------------------------------------
Both glyphs are solid black on a transparent background, so the only thing that
carries information is *how opaque* each pixel is - the colour is a constant
that the tile supplies. And alpha cannot survive the trip through the image
loader anyway: Image.cpp's load_image() sets has_transparency = 0 and converts
straight to 16-bit, so a PNG with transparency comes back as a black square.

Storing the alpha channel directly therefore costs 4 KB per glyph, needs no
decoder at run time, and is exact. A PNG would still have to be decoded and have
its alpha discarded.

The masks are square and each glyph is fitted inside its own at its own aspect,
centred, so blend_mask_glyph() can treat the whole mask as the box it scales
onto the tile and the zero-coverage padding needs no special case.

To change a glyph:

  1. replace the matching file in res/icons/source/
  2. python res/icons/make_icons.py
  3. cmake --build build --config Release
"""

import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
REPO = os.path.dirname(os.path.dirname(HERE))
SOURCE_DIR = os.path.join(HERE, "source")
HEADER = os.path.join(REPO, "MREmu", "NativeApps", "Menu", "IconsData.h")

# (constant prefix, source filename, mask side)
#
# Square, and comfortably larger than the ~48px tile these land on so a
# stepped-up screen still samples from something finer than its own size.
ICONS = (
    ("List", "list-ul.png", 64),
    ("Placeholder", "gamepad.png", 64),
)


def build_mask(alfa, side):
    """Alpha channel fitted into a side x side square, aspect preserved."""
    from PIL import Image

    w, h = alfa.size
    box = max(w, h)
    # The glyph at full alpha on a transparent square, so the LANCZOS downscale
    # averages real coverage on both sides of an edge instead of clamping at the
    # border.
    sq = Image.new("L", (box, box), 0)
    sq.paste(alfa, ((box - w) // 2, (box - h) // 2))
    return sq.resize((side, side), Image.LANCZOS)


def load_source(name):
    from PIL import Image

    path = os.path.join(SOURCE_DIR, name)
    if not os.path.exists(path):
        return None, "missing source: %s" % path

    im = Image.open(path).convert("RGBA")
    alfa = im.getchannel("A")

    # Crop to the glyph. These are icon canvases whose drawing occupies only the
    # middle; keeping the padding would scale the glyph to a fraction of the tile
    # it is meant to fill.
    bbox = alfa.getbbox()
    if bbox is None:
        return None, "source has no visible pixels: %s" % path

    return alfa.crop(bbox), None


def write_header(masks):
    lines = [
        "#pragma once",
        "",
        "// Generated by res/icons/make_icons.py from res/icons/source/.",
        "// Do not edit.",
        "//",
        "// Glyphs the grid draws for itself, each as an 8-bit coverage mask - one",
        "// byte of alpha per pixel, no colour.",
        "//",
        "// PNGs are not used here on purpose. Image.cpp's load_image() discards",
        "// alpha (has_transparency = 0, converted straight to 16-bit), so an",
        "// embedded PNG with transparency would arrive as a black square.",
        "",
        "#include <cstdint>",
        "",
        "namespace NativeApps::Menu::Icons {",
        "",
    ]
    for prefix, side, mask in masks:
        lines.append("inline constexpr int k%sSide = %d;" % (prefix, side))
        lines.append("")
        lines.append("inline constexpr unsigned char k%sMask[k%sSide * k%sSide] = {"
                     % (prefix, prefix, prefix))
        # tobytes(), not getdata(): the latter is deprecated in Pillow 11 and
        # warns on every run, and an "L" image's raw bytes are already the
        # pixel values.
        rows = list(mask.tobytes())
        for y in range(side):
            lines.append("\t" + " ".join(
                "%3d," % v for v in rows[y * side:(y + 1) * side]))
        lines.append("};")
        lines.append("")

    lines.append("} // namespace NativeApps::Menu::Icons")
    lines.append("")
    with open(HEADER, "w", newline="\n") as f:
        f.write("\n".join(lines))


def main():
    try:
        from PIL import Image  # noqa: F401
    except ImportError:
        print("Pillow is required: pip install Pillow", file=sys.stderr)
        return 1

    masks = []
    for prefix, filename, side in ICONS:
        alfa, err = load_source(filename)
        if err:
            print(err, file=sys.stderr)
            return 1
        mask = build_mask(alfa, side)
        masks.append((prefix, side, mask))
        print("%-12s %-16s cropped to %dx%d, %d bytes of coverage"
              % (prefix, filename, alfa.width, alfa.height, side * side))

    write_header(masks)
    print("header : %s" % HEADER)
    return 0


if __name__ == "__main__":
    sys.exit(main())