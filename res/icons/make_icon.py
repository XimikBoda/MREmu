"""Build the list-switch tile's glyph mask for the emulator.

Emits:

  MREmu/NativeApps/Menu/ListIconData.h    an 8-bit coverage mask, not a PNG

Why a mask and not the PNG itself
----------------------------------
The glyph is a solid black shape on a transparent background, so the only thing
that carries information is *how opaque* each pixel is - the colour is a
constant. And alpha cannot survive the trip through the image loader anyway:
Image.cpp's load_image() sets has_transparency = 0 and converts straight to
16-bit, so a PNG with transparency comes back as a black square.

Storing the alpha channel directly therefore costs 4 KB, needs no decoder at
run time, and is exact. A 64x64 one-byte mask against a 7.4 KB PNG that would
still have to be decoded and have its alpha discarded.

The mask is square and the glyph is fitted inside it with its aspect preserved,
centred. The padding is zero coverage, so draw_list_glyph() can treat the whole
mask as the box it scales onto the tile.

To change the glyph:

  1. replace res/icons/source/list-ul.png
  2. python res/icons/make_icon.py
  3. cmake --build build --config Release
"""

import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
REPO = os.path.dirname(os.path.dirname(HERE))
SOURCE = os.path.join(HERE, "source", "list-ul.png")
HEADER = os.path.join(REPO, "MREmu", "NativeApps", "Menu", "ListIconData.h")

# Square, and comfortably larger than the ~48px tile it lands on so that a
# stepped-up screen still samples from something finer than its own size.
SIDE = 64


def build_mask(alfa, w, h, side):
    """Alpha channel fitted into a side x side square, aspect preserved."""
    from PIL import Image

    box = max(w, h)
    # canvas the glyph at full alpha on a transparent square, so the LANCZOS
    # downscale averages real coverage on both sides of an edge instead of
    # clamping at the border.
    sq = Image.new("L", (box, box), 0)
    sq.paste(alfa, ((box - w) // 2, (box - h) // 2))
    return sq.resize((side, side), Image.LANCZOS)


def write_header(mask, side):
    # tobytes(), not getdata(): the latter is deprecated in Pillow 11 and warns
    # on every run, and an "L" image's raw bytes are already the pixel values.
    rows = list(mask.tobytes())
    lines = [
        "#pragma once",
        "",
        "// Generated by res/icons/make_icon.py from res/icons/source/list-ul.png.",
        "// Do not edit.",
        "//",
        "// The glyph on the grid's 'Switch to List View' tile, as an 8-bit",
        "// coverage mask - one byte of alpha per pixel, no colour.",
        "//",
        "// A PNG is not used here on purpose. Image.cpp's load_image() discards",
        "// alpha (has_transparency = 0, converted straight to 16-bit), so an",
        "// embedded PNG with transparency would arrive as a black square.",
        "",
        "#include <cstdint>",
        "",
        "namespace NativeApps::Menu::ListIcon {",
        "",
        "inline constexpr int kSide = %d;" % side,
        "",
        "inline constexpr unsigned char kMask[kSide * kSide] = {",
    ]
    for y in range(side):
        row = rows[y * side:(y + 1) * side]
        lines.append("\t" + " ".join("%3d," % v for v in row))
    lines.append("};")
    lines.append("")
    lines.append("} // namespace NativeApps::Menu::ListIcon")
    lines.append("")
    with open(HEADER, "w", newline="\n") as f:
        f.write("\n".join(lines))


def main():
    try:
        from PIL import Image
    except ImportError:
        print("Pillow is required: pip install Pillow", file=sys.stderr)
        return 1

    if not os.path.exists(SOURCE):
        print("missing source: %s" % SOURCE, file=sys.stderr)
        return 1

    im = Image.open(SOURCE).convert("RGBA")
    alfa = im.getchannel("A")

    # Crop to the glyph. The source is a 512x512 icon canvas whose drawing only
    # occupies the middle ~340x256; keeping the padding would scale the glyph
    # down to a fraction of the tile it is meant to fill.
    box = alfa.getbbox()
    if box is None:
        print("source has no visible pixels: %s" % SOURCE, file=sys.stderr)
        return 1
    alfa = alfa.crop(box)

    mask = build_mask(alfa, alfa.width, alfa.height, SIDE)
    write_header(mask, SIDE)

    print("source : %s (%dx%d, cropped to %dx%d)"
          % (SOURCE, im.width, im.height, alfa.width, alfa.height))
    print("header : %s (%d bytes of coverage)"
          % (HEADER, SIDE * SIDE))
    return 0


if __name__ == "__main__":
    sys.exit(main())