"""Build the app selector's wallpaper asset and embed it for the emulator.

PROVENANCE: a star-field / galaxy wallpaper, already at the display's native
240x320.

Two artefacts come out of this, and they are generated together on purpose:

  res/wallpaper/app_selector.png           the shareable asset
  MREmu/NativeApps/Menu/WallpaperData.h    the same PNG as a byte array

The header exists because the selector is a VXP native app compiled into the
shared library for Android, where there is no asset directory beside the binary
to load a file from. Embedding the PNG keeps it small: the source is
flat-shaded, so it compresses well, and vm_graphic_load_image_FIX decodes it
directly.

To change the wallpaper:

  1. replace res/wallpaper/source/app_selector.jpg
  2. python res/wallpaper/make_wallpaper.py
  3. cmake --build build --config Release

Step 2 is not optional. Regenerating only the PNG would leave the running build
on the old header, which is the kind of drift that is very hard to notice.
"""

import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
REPO = os.path.dirname(os.path.dirname(HERE))
SOURCE = os.path.join(HERE, "source", "app_selector.jpg")
ASSET = os.path.join(HERE, "app_selector.png")
HEADER = os.path.join(REPO, "MREmu", "NativeApps", "Menu", "WallpaperData.h")

# The emulated display is a fixed 240x320. The wallpaper is prepared at that
# size and stretched if the window is stepped up, which is the right way round:
# the triangles are large and flat-shaded, so a blocky upscale in a dimmed
# background is invisible, whereas a larger master costs the embedded header.
W, H = 240, 320


def png_bytes(rgb, w, h):
    raise NotImplementedError


def write_header(data, w, h):
    lines = [
        "#pragma once",
        "",
        "// Generated by res/wallpaper/make_wallpaper.py from",
        "// res/wallpaper/source/app_selector.jpg. Do not edit.",
        "//",
        "// The app selector's wallpaper as a PNG, embedded so it is available on",
        "// Android, where a VXP native app has no asset directory to load from.",
        "// Decoded once at start-up with vm_graphic_load_image_FIX.",
        "",
        "// PROVENANCE: a star-field / galaxy wallpaper.",
        "// See res/wallpaper/README.md.",
        "",
        "#include <cstdint>",
        "",
        "namespace NativeApps::Menu::Wallpaper {",
        "",
        "inline constexpr int kWidth = %d;" % w,
        "inline constexpr int kHeight = %d;" % h,
        "",
        "inline constexpr unsigned char kPng[] = {",
    ]
    for i in range(0, len(data), 16):
        lines.append("\t" + ", ".join("0x%02x" % b for b in data[i:i + 16]) + ",")
    lines.append("};")
    lines.append("")
    lines.append("inline constexpr int kPngSize = sizeof(kPng);")
    lines.append("")
    lines.append("} // namespace NativeApps::Menu::Wallpaper")
    lines.append("")
    with open(HEADER, "w", newline="\n") as f:
        f.write("\n".join(lines))


def main():
    try:
        from PIL import Image
    except ImportError:
        print("Pillow is required: pip install Pillow", file=sys.stderr)
        return 1

    if not os.path.exists(SOURCE):
        print("missing source: %s" % SOURCE, file=sys.stderr)
        return 1

    # LANCZOS, not NEAREST: the source is nearly five times the display size and
    # its triangles have hard edges, so point sampling would alias them badly.
    im = Image.open(SOURCE).convert("RGB").resize((W, H), Image.LANCZOS)

    # Written by Pillow rather than by hand. A hand-rolled palette PNG here was
    # accepted by every reader except the one that matters: stb_image, inside
    # SFML, behind vm_graphic_load_image_FIX. Truecolour is both what it
    # definitely accepts and simple enough not to get subtly wrong.
    im.save(ASSET, format="PNG", optimize=True)
    with open(ASSET, "rb") as f:
        data = f.read()

    write_header(data, W, H)

    print("source : %s" % SOURCE)
    print("asset  : %s (%d bytes, %dx%d)" % (ASSET, len(data), W, H))
    print("header : %s" % HEADER)
    return 0


if __name__ == "__main__":
    sys.exit(main())